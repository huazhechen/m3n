// M3N slim build of Verovio 6.2.0. See docs/VEROVIO_BUILD.md for prerequisites.
import { createHash } from 'node:crypto'
import { cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import { spawnSync } from 'node:child_process'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const commit = '43f806031bfff2c64003fc8ddd9910820445f6ab'
const sourceSha256 = '9ec55723381105f14453d5d182d09877d75d6f18c31ef4119164d74132a47eca'
const emscriptenVersion = '4.0.20'
const work = resolve(root, '.tmp/verovio-build')
const source = resolve(work, `verovio-${commit}`)
const build = resolve(work, 'build')
const vendor = resolve(root, 'packages/score-renderer/vendor/verovio')
const notices = resolve(root, 'public/licenses/verovio')

function run(command, args, options = {}) {
  const result = spawnSync(command, args, { cwd: work, encoding: 'utf8', stdio: 'inherit', ...options })
  if (result.error) throw result.error
  if (result.status !== 0) throw new Error(`${command} exited with ${result.status}`)
  return result.stdout
}

const archive = resolve(notices, 'verovio-6.2.0-source.tar.gz')
const archiveBytes = await readFile(archive)
if (createHash('sha256').update(archiveBytes).digest('hex') !== sourceSha256) {
  throw new Error('Verovio source archive checksum mismatch')
}
await mkdir(work, { recursive: true })
const compiler = run('em++', ['--version'], { stdio: 'pipe' })
if (!compiler.split('\n')[0].includes(` ${emscriptenVersion} (`)) {
  throw new Error(`Use Emscripten ${emscriptenVersion}; found ${compiler.split('\n')[0]}`)
}
run('tar', ['-xzf', archive, '-C', work])
// Avoid deriving the upstream version from the surrounding M3N checkout.
const cmakeFile = resolve(source, 'cmake/CMakeLists.txt')
const cmake = await readFile(cmakeFile, 'utf8')
const gitVersionStep = /execute_process\(\s*COMMAND \.\.\/tools\/get_git_commit\.sh[\s\S]*?\n\)/
if (!gitVersionStep.test(cmake)) throw new Error('Upstream CMake version step changed')
await writeFile(cmakeFile, cmake.replace(gitVersionStep, '# M3N: pinned version header is generated by build-verovio.mjs.'))
await writeFile(resolve(source, 'include/vrv/git_commit.h'), `#define GIT_COMMIT "-${commit.slice(0, 7)}"\n`)

// Liberation's optional embedded text font is never enabled by M3N.
// Keep data/text (Times metrics) and both required music fonts untouched.
const excludedFonts = ['Gootville', 'Leland', 'Petaluma', 'Liberation']
// 6.2.0 has incomplete MusicXML/editor exclusion guards; retain those features.
const disabledFeatures = ['DARMS', 'PAE', 'ABC', 'GABC', 'MXL', 'HUMDRUM']
const flags = ['-O3', '-DNDEBUG', '-std=c++20', '-sSTRICT=1', '-fwasm-exceptions']
run('emcmake', ['cmake', '-S', resolve(source, 'cmake'), '-B', build,
  '-DBUILD_AS_WASM=ON', '-DNO_MUSICXML_SUPPORT=OFF', '-DNO_EDIT_SUPPORT=OFF', `-DCMAKE_CXX_FLAGS=${flags.join(' ')}`,
  ...disabledFeatures.map(feature => `-DNO_${feature}_SUPPORT=ON`),
])
run('cmake', ['--build', build, '--parallel', process.env.VEROVIO_BUILD_JOBS ?? '6'])

const resources = resolve(work, 'data')
await rm(resources, { recursive: true, force: true })
await cp(resolve(source, 'data'), resources, { recursive: true })
for (const entry of await readdir(resources)) {
  if (excludedFonts.some(font => entry === font || entry.startsWith(`${font}.`))) {
    await rm(resolve(resources, entry), { recursive: true, force: true })
  }
}
await mkdir(vendor, { recursive: true })
const output = resolve(work, 'verovio-module.mjs')
run('em++', [resolve(build, 'libverovio.a'), ...flags,
  '-sWASM=1', '-sINITIAL_MEMORY=128MB', '-sSTACK_SIZE=64MB', '-sALLOW_MEMORY_GROWTH=1',
  '-sSINGLE_FILE=1', '-sINCOMING_MODULE_JS_API=onRuntimeInitialized',
  '-sMODULARIZE=1', '-sEXPORT_ES6=1', '-sEXPORT_NAME=createVerovioModule',
  `-sEXPORTED_FUNCTIONS=@${resolve(source, 'emscripten/exports.txt')}`,
  '-sEXPORTED_RUNTIME_METHODS=["cwrap","HEAPU8"]', '--embed-file', 'data/', '-o', output,
])
const bytes = await readFile(output)
await writeFile(resolve(vendor, 'verovio-module.mjs'), Buffer.concat([
  Buffer.from('/*! Verovio 6.2.0, LGPL-3.0-or-later. M3N slim build; license, source and recipe: /licenses/verovio/README.txt */\n'), bytes,
]))
const artifact = await readFile(resolve(vendor, 'verovio-module.mjs'))
await writeFile(resolve(vendor, 'build.json'), `${JSON.stringify({
  version: '6.2.0', commit, sourceSha256, emscriptenVersion,
  excludedFonts, disabledFeatures,
  moduleSha256: createHash('sha256').update(artifact).digest('hex'),
}, null, 2)}\n`)
// Ship the exact recipe beside the corresponding source for LGPL recipients.
await cp(fileURLToPath(import.meta.url), resolve(notices, 'build-verovio.mjs'))
console.log(`Built ${artifact.length.toLocaleString()} bytes; ${vendor}`)
