"""Generate per-score browser fonts from the offline Source Han Sans font.

Requires fonttools 4.68.0. No network access. The source font is SIL OFL.
The full TrueType font is only a fallback for user text outside preset subsets.
"""
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parent.parent
assets = root / 'packages/numbered-notation/src/font-assets'
assets.mkdir(exist_ok=True)
source = root / 'tools/fonts/NotoSansCJKsc-Regular.otf'
font = TTFont(source, recalcTimestamp=False)
charset = ''.join(chr(c) for c in font.getBestCmap())
all_chars = root / '.tmp/score-fonts/all-characters.txt'
all_chars.parent.mkdir(parents=True, exist_ok=True)
all_chars.write_text(charset)
full = assets / 'NotoSansSC-full.ttf'
fingerprint_file = root / '.tmp/score-fonts/full-source.sha256'
source_hash = hashlib.sha256(source.read_bytes()).hexdigest()
if not full.exists() or not fingerprint_file.exists() or fingerprint_file.read_text() != source_hash:
    subprocess.run([sys.executable, str(root / 'tools/subset-builtin-pdf-font.py'), str(source), str(all_chars), str(full)], check=True)
    fingerprint_file.write_text(source_hash)

full_bytes = full.read_bytes()
manifest = []
base = TTFont(full, recalcTimestamp=False)
cmap = base.getBestCmap()

def save_subset(name, text):
    codes = sorted({ord(c) for c in text if ord(c) in cmap})
    target = assets / name
    f = TTFont(full, recalcTimestamp=False)
    options = subset.Options()
    options.layout_features = []
    options.recalc_timestamp = False
    sub = subset.Subsetter(options=options)
    sub.populate(unicodes=codes)
    sub.subset(f)
    f['glyf'].padding = 4
    f.save(target)
    web_target = target.with_suffix('.woff2')
    web_font = TTFont(target, recalcTimestamp=False)
    web_font.flavor = 'woff2'
    web_font.save(web_target)
    manifest.append(dict(file=name, web_file=web_target.name, characters=''.join(chr(c) for c in codes), bytes=target.stat().st_size, web_bytes=web_target.stat().st_size))

# Source text is a conservative superset of displayed metadata and lyrics.
labels = '演唱作词作曲音域：'
for path in sorted([*root.glob('src/scores/*.m3n'), *root.glob('src/works/*.m3n'), *root.glob('src/examples/*.m3n')]):
    source = path.read_text()
    text = labels + ''.join(chr(c) for c in range(32, 127)) + source
    digest = hashlib.sha256(''.join(sorted(set(text))).encode()).hexdigest()[:16]
    name = f'NotoSansSC-{digest}.ttf'
    if not any(item['file'] == name for item in manifest):
        save_subset(name, text)
manifest.append(dict(file=full.name, characters=charset, bytes=len(full_bytes)))

# Extract the existing unmodified Medium face used by music numerals.
data = (root / 'packages/numbered-notation/src/font-data.ts').read_text()
import base64
(assets / 'BarlowSemiCondensed-Medium.ttf').write_bytes(base64.b64decode(re.search(r'base64,([A-Za-z0-9+/=]+)', data)[1]))
latin = []
file = 'BarlowSemiCondensed-Medium.ttf'
f = TTFont(assets / file)
web_file = file.replace('.ttf', '.woff2')
f.flavor = 'woff2'
f.save(assets / web_file)
latin.append(dict(file=file, web_file=web_file, weight=500, style='normal', characters=''.join(chr(c) for c in TTFont(assets / file).getBestCmap())))
bravura = TTFont(assets / 'Bravura.woff2', recalcTimestamp=False)
# fontkit can read WOFF2 outlines, but its TrueType subset writer loses the
# transformed glyf data. Export the equivalent uncompressed face for PDF;
# browsers continue downloading the original WOFF2 through webUrl.
bravura.flavor = None
# Its short-loca subset writer also assumes even glyph offsets. Preserve the
# outlines while padding each source glyph to avoid truncating odd offsets.
bravura['glyf'].padding = 2
bravura.save(assets / 'Bravura.ttf')
resources = root / 'packages/numbered-notation/src/font-resources.ts'
lines = ['// Generated by tools/prepare-score-fonts.py. Do not edit.']
for name, entries in [('LATIN_FONTS', latin), ('CJK_FONTS', manifest), ('BRAVURA_FONTS', [dict(file='Bravura.ttf', web_file='Bravura.woff2', characters=''.join(chr(c) for c in bravura.getBestCmap()))])]:
    lines.append(f'export const {name} = [')
    for entry in entries:
        item = json.dumps({key: value for key, value in entry.items() if key != 'web_file'}, ensure_ascii=True)
        urls = ', url: new URL(' + json.dumps('./font-assets/' + entry['file']) + ', import.meta.url).href'
        if entry.get('web_file'):
            urls += ', webUrl: new URL(' + json.dumps('./font-assets/' + entry['web_file']) + ', import.meta.url).href'
        lines.append('  { ...' + item + urls + ' },')
    lines.append('] as const')
resources.write_text('\n'.join(lines) + '\n')
active = {item['file'] for item in manifest}
for path in assets.glob('NotoSansSC-*.ttf'):
    if path.name not in active: path.unlink()
active_web = {item['web_file'] for item in manifest if item.get('web_file')}
for path in assets.glob('NotoSansSC-*.woff2'):
    if path.name not in active_web: path.unlink()
for path in assets.glob('BarlowSemiCondensed-*.ttf'):
    if path.name != file: path.unlink()
for path in assets.glob('BarlowSemiCondensed-*.woff2'):
    if path.name != web_file: path.unlink()
print(json.dumps({'singleScoreFonts': len(manifest) - 1, 'singleScoreMinBytes': min(x['bytes'] for x in manifest[:-1]), 'singleScoreMaxBytes': max(x['bytes'] for x in manifest[:-1]), 'singleScoreMinWebBytes': min(x['web_bytes'] for x in manifest[:-1]), 'singleScoreMaxWebBytes': max(x['web_bytes'] for x in manifest[:-1]), 'fallbackBytes': len(full_bytes)}, indent=2))
