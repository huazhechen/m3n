import { chromium, expect } from '@playwright/test'
import { pathToFileURL } from 'node:url'
import { resolve } from 'node:path'
import { mkdir, readFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
await mkdir('.tmp/offline-check', { recursive: true })
const executablePath = process.env.M3N_BROWSER_PATH ?? (existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined)
const browser = await chromium.launch({ executablePath, headless: true, args: ['--autoplay-policy=no-user-gesture-required'] })
const context = await browser.newContext({ offline: true, acceptDownloads: true })
const page = await context.newPage()
const errors = [], requests = []
page.on('pageerror', e => errors.push(e.message))
page.on('request', r => { if (/^https?:/.test(r.url())) requests.push(r.url()) })
page.on('console', m => { if (m.type() === 'error') console.log('console:',m.text().slice(0,180)) })
const file = resolve(process.argv[2] ?? 'offline/m3n.html')
const html = await readFile(file, 'utf8')
expect(html).not.toMatch(/<script[^>]+src=/i)
expect(html).not.toMatch(/data:font\/otf;base64,/)
expect(Buffer.byteLength(html)).toBeLessThan(8 * 1024 * 1024)
const url = pathToFileURL(file).href
try {
 await page.goto(`${url}#/scores/na_xie_nian_01`)
 await expect(page.locator('.score-paper svg[data-engine="m3n"]')).toBeVisible({ timeout: 30000 })
 console.log('Offline score renders')
 await page.getByRole('button', { name: '播放', exact: true }).click()
 await expect(page.locator('.score-paper .is-playing').first()).toBeVisible({ timeout: 30000 })
 await page.getByRole('button', { name: '暂停', exact: true }).click()
 console.log('Synthetic playback works')
 await page.getByRole('button', { name: '乐谱设置', exact: true }).click()
 await page.getByRole('switch', { name: '钢琴音色', exact: true }).click()
 await expect(page.getByRole('button', { name: '后台加载', exact: true })).toHaveCount(0, { timeout: 30000 })
 if (!await page.getByRole('switch', { name: '钢琴音色', exact: true }).isVisible()) await page.getByRole('button', { name: '乐谱设置', exact: true }).click()
 await expect(page.getByRole('switch', { name: '钢琴音色', exact: true })).toHaveAttribute('aria-checked', 'true', { timeout: 30000 })
 await page.getByRole('button', { name: '播放', exact: true }).click()
 await expect(page.locator('.score-paper .is-playing').first()).toBeVisible({ timeout: 30000 })
 await page.getByRole('button', { name: '暂停', exact: true }).click()
 console.log('Piano playback works')
 for (const format of ['SVG','PNG','PDF']) {
   await page.getByRole('button', { name: '打印', exact: true }).click()
   const [download] = await Promise.all([page.waitForEvent('download', { timeout: 60000 }), page.getByRole('button', { name: format, exact: true }).click()])
   expect(await download.failure()).toBeNull()
   await download.saveAs(`.tmp/offline-check/export-${format.toLowerCase()}.${format.toLowerCase()}`)
   const bytes = await readFile(`.tmp/offline-check/export-${format.toLowerCase()}.${format.toLowerCase()}`)
   expect(bytes.length).toBeGreaterThan(100)
   if (format === 'PDF') expect(bytes.subarray(0, 5).toString()).toBe('%PDF-')
   if (format === 'PNG') expect([...bytes.subarray(0, 4)]).toEqual([137, 80, 78, 71])
   if (format === 'SVG') expect(bytes.toString()).toContain('<svg')
   console.log(`${format} export works`)
 }
 await page.getByRole('link', { name: '编辑', exact: true }).click()
 await page.getByLabel('M3N source').fill('{title=离线测试}{4/4}\nN: 1 2 3 4 |||\nL: 离线测试')
 await expect(page.locator('.score-paper')).toContainText('离线测试')
 await expect(page.getByRole('button', { name: '分享', exact: true })).toHaveCount(0)
 await page.getByRole('button', { name: '保存', exact: true }).click()
 await expect(page.locator('.score-paper')).toContainText('离线测试')
 await page.reload()
 await expect(page.locator('.score-paper')).toContainText('离线测试')
 console.log('Editor, local save and reload work')
 await page.getByRole('link', { name: '乐谱库', exact: true }).click()
 await expect(page.locator('main')).toContainText('那些年')
 console.log('Library works')
 await page.getByRole('link', { name: '简谱转换', exact: true }).click()
 await expect(page.getByLabel('Happi123 source')).toBeVisible()
 await page.getByRole('button', { name: '转换', exact: true }).click()
 await expect(page.getByRole('textbox', { name: 'M3N 内容', exact: true })).toHaveValue(/\{title=/)
 await page.goto(`${url}#/?doc=manual`)
 await expect(page.locator('main')).toContainText('后置标记', { timeout: 15000 })
 await page.goto(`${url}#/?doc=guide`)
 await expect(page.locator('.book-layout')).toBeVisible({ timeout: 15000 })
 expect(await page.locator('#m3n-licenses').textContent()).toContain('SIL')
 expect(requests).toEqual([])
 expect(errors).toEqual([])
 console.log('No HTTP requests or page errors')
} catch (error) {
 await page.screenshot({ path: '.tmp/offline-check/failure.png' }).catch(() => {})
 console.error(String(error).slice(0, 1200))
 process.exitCode = 1
} finally { await browser.close() }
