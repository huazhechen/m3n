import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('editor provides highlighting, completions, diagnostic navigation and keyboard resizing', async ({ page }, info) => {
  await page.goto('/editor')
  const editor = page.getByRole('textbox', { name: 'M3N source', exact: true })
  await editor.fill('{4/4}\nN: 1 2 3 4 5 |||')
  await expect(page.locator('.cm-gutter.cm-lineNumbers')).toBeVisible()
  await expect(page.locator('.cm-content span').first()).toBeVisible()
  const diagnostic = page.locator('.diagnostic-link').filter({ hasText: '超出' }).first()
  await expect(diagnostic).toBeVisible()
  await diagnostic.click()
  await expect(editor).toBeFocused()
  const split = page.getByRole('separator', { name: '调整源码与预览宽度' })
  await split.focus(); await split.press('ArrowRight')
  await expect(split).toHaveAttribute('aria-valuenow', '55')
  await editor.fill('{key')
  await editor.press('Control+Space')
  await expect(page.getByRole('listbox')).toBeVisible()
  await expect(page.getByRole('option', { name: 'key=C', exact: true })).toBeVisible()
  await page.screenshot({ path: info.outputPath('editor-desktop.png') })
})

test('mobile editor switches panes without losing input; catalog fills and filters the viewport', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/editor')
  const editor = page.getByRole('textbox', { name: 'M3N source', exact: true })
  await editor.fill('{title=手机试改}{4/4}\nN: 1 2 3 4 |||')
  await page.getByRole('tab', { name: '预览', exact: true }).click()
  await expect(page.locator('.score-paper')).toContainText('手机试改')
  await expect(editor).not.toBeVisible()
  await expect(page.locator('.score-paper svg').first()).toBeVisible()
  await expect(page.locator('.score-paper')).not.toHaveAttribute('aria-busy', 'true')
  const bounds = await page.locator('.score-paper svg').first().boundingBox()
  expect(bounds!.width).toBeGreaterThan(290)
  expect(bounds!.width).toBeLessThan(390)
  await page.screenshot({ path: info.outputPath('editor-mobile.png') })
  await page.getByRole('tab', { name: '源码', exact: true }).click()
  await expect(editor).toHaveText('{title=手机试改}{4/4}\nN: 1 2 3 4 |||', { useInnerText: true })
  await page.goto('/scores')
  await expect(page.getByRole('navigation', { name: '最近编辑' })).toContainText('手机试改')
  const card = page.locator('.score-list .score-card').first()
  expect((await card.boundingBox())!.width).toBeGreaterThan(320)
  await page.getByLabel('乐谱来源').selectOption('local')
  await expect(page.locator('.score-list .score-card')).toHaveCount(0)
  await page.getByLabel('乐谱来源').selectOption('preset')
  await page.getByLabel('筛选拍号').selectOption('6/8')
  await expect(page.locator('.score-list .score-card').first()).toContainText('6/8')
  await page.getByRole('button', { name: '紧凑列表' }).click()
  await expect(page.locator('.score-list')).toHaveClass(/is-compact-list/)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('library-mobile.png') })
})

test('practice starts at the selected measure and loops with independent staff muting', async ({ page }) => {
  await page.goto('/editor')
  await page.getByRole('textbox', { name: 'M3N source' }).fill('{4/4}{120qpm}\nN: 1 2 3 4 | 5 6 7 1e | 2e 3e 4e 5e |||\nB: 1d 2d 3d 4d | 5d 6d 7d 1 | 2 3 4 5 |||')
  await page.getByRole('radio', { name: '简谱', exact: true }).check()
  const paper = page.locator('.score-paper')
  await expect(paper.locator('svg[data-engine="jpfun"]')).toBeVisible()
  await paper.locator('[data-m3n-id="m3n-e-9"] text').first().click()
  await page.getByRole('button', { name: '练习设置', exact: true }).click()
  await page.getByRole('checkbox', { name: '旋律静音', exact: true }).check()
  await page.getByRole('button', { name: '从选中小节播放' }).click()
  await expect(page.getByRole('button', { name: '暂停', exact: true })).toBeVisible()
  await expect.poll(async () => Number(await page.getByRole('slider', { name: '播放位置', exact: true }).inputValue())).toBeGreaterThan(250)
  await page.getByRole('button', { name: '暂停', exact: true }).click()
  await page.getByRole('slider', { name: '播放位置', exact: true }).focus()
  await page.getByRole('slider', { name: '播放位置', exact: true }).press('Home')
  await page.getByRole('button', { name: '设为 A', exact: true }).click()
  for (let index = 0; index < 2; index++) await page.getByRole('slider', { name: '播放位置', exact: true }).press('ArrowRight')
  await page.getByRole('button', { name: '设为 B', exact: true }).click()
  await page.getByRole('checkbox', { name: 'A–B 循环', exact: true }).check()
  await expect(page.getByRole('checkbox', { name: 'A–B 循环', exact: true })).toBeChecked()
  await page.getByRole('checkbox', { name: '低音静音', exact: true }).check()
  await page.getByRole('checkbox', { name: '播放跟随', exact: true }).uncheck()
  await page.getByRole('button', { name: '恢复默认', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: '旋律静音', exact: true })).not.toBeChecked()
})

test('staff SVG and multipage PDF retain Chinese outlines and all written measures', async ({ page }, info) => {
  test.setTimeout(90_000)
  await page.goto('/editor')
  await page.getByRole('textbox', { name: 'M3N source' }).fill(`{title=中文矢量验证}{4/4}\nN: ${Array.from({ length: 64 }, () => '1 2 3 4 |').join(' ')}||\nL: 春天来了`)
  await page.getByRole('button', { name: '保存并预览', exact: true }).click()
  for (const format of ['SVG 矢量图（连续）', 'PDF（A4 分页）']) {
    await page.getByRole('button', { name: '打印', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByRole('radio', { name: format, exact: true }).check()
    await dialog.getByRole('spinbutton', { name: '打印宽度' }).fill('600')
    await expect(dialog.locator('.export-preview')).toHaveAttribute('aria-busy', 'false')
    const count = await dialog.locator('.export-preview-page').count()
    if (format.startsWith('PDF')) expect(count).toBeGreaterThan(1)
    const downloading = page.waitForEvent('download')
    await dialog.getByRole('button', { name: '确认并下载' }).click()
    const download = await downloading
    const file = info.outputPath(download.suggestedFilename()); await download.saveAs(file)
    const bytes = await readFile(file)
    if (format.startsWith('SVG')) {
      const svg = bytes.toString()
      expect(svg).toContain('data-outlined-text="中文矢量验证"')
      expect(svg).toContain('m3n-e-256')
      expect(svg).not.toContain('<text')
    } else {
      const pdf = bytes.toString('latin1')
      expect((pdf.match(/\/Type \/Page\b/g) ?? []).length).toBe(count)
      expect(pdf).not.toContain('/Subtype /Image')
      expect(bytes.length).toBeGreaterThan(20_000)
    }
  }
})
