import { expect, test } from '@playwright/test'
import { openScoreSettings } from './score-settings'

test('header range uses numbered pitches and follows fixed do and transposition', async ({ page }, info) => {
  await page.goto('/editor')
  await page.getByLabel('M3N source').fill('{key=D}{4/4}{120qpm}\nN: 1d 2 3 7e |||\nB: 1dd^ 1dd^ |')
  const paper = page.locator('.score-paper')
  const low = paper.locator('[data-m3n-role="pitch-range-low"]')
  const high = paper.locator('[data-m3n-role="pitch-range-high"]')
  await expect(low).toHaveText('1')
  await expect(high).toHaveText('7')
  await expect(low.locator('circle')).toHaveCount(1)
  await expect(high.locator('circle')).toHaveCount(1)
  await expect(paper).not.toContainText('音域')
  await openScoreSettings(page)
  await page.getByRole('switch', { name: '固定调记谱' }).click()
  await expect(low).toHaveText('2')
  await expect(high).toHaveText('1')
  await expect(high.locator('circle')).toHaveCount(2)
  await openScoreSettings(page)
  await page.getByRole('button', { name: /^移调，当前/ }).click()
  await page.getByRole('dialog', { name: '选择调性' }).getByRole('button', { name: 'C大调', exact: true }).click()
  await expect(low).toHaveText('1')
  await expect(high).toHaveText('7')
  await expect(high.locator('circle')).toHaveCount(1)
  await openScoreSettings(page)
  await page.getByRole('switch', { name: '固定调记谱' }).click()
  await expect(low).toHaveText('1')
  await expect(high).toHaveText('7')
  await page.setViewportSize({ width: 320, height: 700 })
  await page.getByRole('tab', { name: '预览', exact: true }).click()
  await openScoreSettings(page)
  await page.getByRole('slider', { name: '乐谱宽度' }).fill('320')
  await expect(paper).not.toHaveAttribute('aria-busy', 'true')
  const svg = paper.locator('svg').first()
  await svg.screenshot({ path: info.outputPath('pitch-range-320.png') })
  const positions = await svg.evaluate(element => {
    const range = element.querySelector('[data-m3n-role="pitch-range-low"]')!.getBoundingClientRect()
    const high = element.querySelector('[data-m3n-role="pitch-range-high"]')!.getBoundingClientRect()
    const tempo = [...element.querySelectorAll('text')].find(node => node.textContent === '= 120')!.getBoundingClientRect()
    const bounds = element.getBoundingClientRect()
    return { low: range.left, tempo: tempo.right, right: high.right, boundary: bounds.right }
  })
  expect(positions.low).toBeGreaterThan(positions.tempo)
  expect(positions.right).toBeLessThanOrEqual(positions.boundary)
  await page.getByRole('tab', { name: '源码', exact: true }).click()
  await page.getByLabel('M3N source').fill('{4/4}\nN: 0 0 0 0 |||')
  await expect(low).toHaveCount(0)
  await expect(high).toHaveCount(0)
})
