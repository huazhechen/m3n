import { expect, test } from '@playwright/test'

test('synthetic playback fetches no soundfont; selected samples persist and work from cache after reload', async ({ page }) => {
  const samples: string[] = []
  page.on('request', request => { if (/\.sf3(?:\?|$)/.test(request.url())) samples.push(request.url()) })
  await page.goto('/scores/huan_le_song_01')
  await page.getByRole('button', { name: '播放设置', exact: true }).click()
  const tone = page.getByRole('combobox', { name: '播放音色' })
  const play = page.getByRole('button', { name: '播放', exact: true })
  const pause = page.getByRole('button', { name: '暂停', exact: true })
  await expect(tone).toHaveValue('synth')
  await page.getByRole('dialog', { name: '播放设置' }).getByRole('button', { name: '关闭', exact: true }).click()
  await play.click()
  await expect(pause).toBeVisible({ timeout: 30_000 })
  expect(samples).toHaveLength(0)
  const position = page.getByRole('slider', { name: '播放位置' })
  await expect.poll(async () => Number(await position.inputValue())).toBeGreaterThan(0)
  await page.getByRole('button', { name: '播放设置', exact: true }).click()
  await tone.selectOption('piano')
  await expect(page.getByRole('status').filter({ hasText: '音色已就绪' })).toBeVisible()
  await page.getByRole('dialog', { name: '播放设置' }).getByRole('button', { name: '关闭', exact: true }).click()
  await expect(pause).toBeEnabled()
  await expect.poll(async () => Number(await position.inputValue())).toBeGreaterThan(0)
  expect(samples.filter(url => /Piano-/.test(url))).toHaveLength(1)
  await page.getByRole('button', { name: '播放设置', exact: true }).click()
  await tone.selectOption('harmonica')
  await expect(page.getByRole('status').filter({ hasText: '音色已就绪' })).toBeVisible()
  await page.getByRole('dialog', { name: '播放设置' }).getByRole('button', { name: '关闭', exact: true }).click()
  await expect(pause).toBeEnabled()
  expect(samples.filter(url => /Harmonica-/.test(url))).toHaveLength(1)
  await pause.click()
  expect(await page.evaluate(() => localStorage.getItem('m3n:playback-tone'))).toBe('harmonica')
  expect(await page.evaluate(async () => (await (await caches.open('m3n-soundfonts-v1')).keys()).length)).toBe(2)
  const downloaded = samples.length
  await page.route('**/*.sf3', route => route.abort())
  await page.reload()
  await page.getByRole('button', { name: '播放设置', exact: true }).click()
  await expect(tone).toHaveValue('harmonica')
  await expect(page.getByRole('status').filter({ hasText: '音色已就绪' })).toBeVisible()
  await page.getByRole('dialog', { name: '播放设置' }).getByRole('button', { name: '关闭', exact: true }).click()
  await play.click()
  await expect(pause).toBeVisible()
  await page.getByRole('button', { name: '播放设置', exact: true }).click()
  await tone.selectOption('piano')
  await page.getByRole('dialog', { name: '播放设置' }).getByRole('button', { name: '关闭', exact: true }).click()
  await expect(pause).toBeEnabled()
  expect(samples).toHaveLength(downloaded)
  await pause.click()
  await page.getByRole('button', { name: '播放设置', exact: true }).click()
  await page.getByRole('button', { name: '恢复默认', exact: true }).click()
  await expect(tone).toHaveValue('synth')
  await page.reload()
  await page.getByRole('button', { name: '播放设置', exact: true }).click()
  await expect(tone).toHaveValue('synth')
})

test('failed tone downloads expose retry, and switching to synth supersedes a pending download', async ({ page }) => {
  await page.goto('/scores/huan_le_song_01')
  await page.getByRole('button', { name: '播放设置', exact: true }).click()
  const tone = page.getByRole('combobox', { name: '播放音色' })
  await page.route('**/*Harmonica-*.sf3', route => route.fulfill({ status: 503, body: 'unavailable' }))
  await tone.selectOption('harmonica')
  await expect(page.getByRole('status').filter({ hasText: '无法下载口琴音色' })).toBeVisible()
  await page.unroute('**/*Harmonica-*.sf3')
  await page.getByRole('button', { name: '重试加载音色' }).click()
  await expect(page.getByRole('status').filter({ hasText: '音色已就绪' })).toBeVisible()
  let release: () => void = () => undefined
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/*Piano-*.sf3', async route => { await gate; await route.continue() })
  await tone.selectOption('piano')
  await expect(page.getByRole('status').filter({ hasText: '正在加载音色' })).toBeVisible()
  await tone.selectOption('synth')
  await page.getByRole('dialog', { name: '播放设置' }).getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByRole('button', { name: '播放', exact: true }).click()
  await expect(page.getByRole('button', { name: '暂停', exact: true })).toBeEnabled({ timeout: 30_000 })
  release()
  await page.getByRole('button', { name: '播放设置', exact: true }).click()
  await expect(tone).toHaveValue('synth')
  expect(await page.evaluate(() => localStorage.getItem('m3n:playback-tone'))).toBe('synth')
})
