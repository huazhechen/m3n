import { expect, test } from '@playwright/test'

test('library groups follow the index, support keyboard jumps and update with search', async ({ page }, info) => {
  await page.goto('/scores')
  const index = page.getByRole('navigation', { name: '乐谱首字母索引' })
  await expect(index).toBeVisible()
  const initials = await index.locator('button').allTextContents()
  expect(initials.length).toBeGreaterThan(10)
  expect(await page.locator('[data-library-initial]').evaluateAll(groups => groups.map(group => (group as HTMLElement).dataset.libraryInitial)))
    .toEqual(initials)
  await page.screenshot({ path: info.outputPath('library-desktop.png') })
  const target = index.getByRole('button', { name: '跳至 X 组', exact: true })
  await target.focus()
  await page.keyboard.press('Enter')
  await expect(target).toHaveAttribute('aria-current', 'location')
  await expect(page.locator('#library-group-X')).toBeInViewport()
  await page.getByRole('searchbox', { name: '搜索乐谱' }).fill('小星星')
  await expect(index).toHaveCount(0)
  await expect(page.locator('.library-group')).toHaveCount(1)
  await expect(page.locator('.library-group-heading')).toHaveText('X')
  await page.getByRole('searchbox', { name: '搜索乐谱' }).fill('zzzzzzzz')
  await expect(page.locator('.library-group')).toHaveCount(0)
  await expect(page.getByText('没有找到匹配的乐谱。')).toBeVisible()
})

test('mobile index can be dragged and leaves room for cards', async ({ browser }, info) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  const page = await context.newPage()
  await page.goto('/scores')
  const index = page.getByRole('navigation', { name: '乐谱首字母索引' })
  await expect(index).toBeVisible()
  await page.screenshot({ path: info.outputPath('library-mobile.png') })
  // Check real touch activation before exercising captured pointer dragging.
  await index.getByRole('button', { name: '跳至 X 组', exact: true }).tap()
  await expect(page.locator('#library-group-X')).toBeInViewport()
  const first = await index.locator('button').first().boundingBox()
  const last = await index.locator('button').last().boundingBox()
  expect(first).toBeTruthy()
  expect(last).toBeTruthy()
  await page.mouse.move(first!.x + first!.width / 2, first!.y + first!.height / 2)
  await page.mouse.down()
  await page.mouse.move(last!.x + last!.width / 2, last!.y + last!.height / 2, { steps: 12 })
  await expect(page.locator('.library-index-preview')).toHaveText(await index.locator('button').last().innerText())
  await expect(page.locator('[data-library-initial]').last()).toBeInViewport()
  await page.mouse.up()
  await expect(index.locator('button').last()).toHaveAttribute('aria-current', 'location')
  await expect(page.locator('.library-index-preview')).toHaveCount(0)
  const rail = await index.boundingBox()
  const card = await page.locator('.score-list .score-card').last().boundingBox()
  expect(card!.x + card!.width).toBeLessThanOrEqual(rail!.x)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await context.close()
})

test('letter rail stays inside a narrow landscape viewport', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 667, height: 320 }, isMobile: true, hasTouch: true })
  const page = await context.newPage()
  await page.goto('/scores')
  const rail = page.getByRole('navigation', { name: '乐谱首字母索引' })
  await expect(rail).toBeVisible()
  const bounds = (await rail.boundingBox())!
  expect(bounds.y).toBeGreaterThanOrEqual(0)
  expect(bounds.y + bounds.height).toBeLessThanOrEqual(320)
  await rail.locator('button').last().tap()
  await expect(page.locator('[data-library-initial]').last()).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await context.close()
})

for (const width of [390, 1280]) {
  test(`category view preserves every score and hides the letter index at ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/scores')
    await expect(page.locator('.score-list a').first()).toBeVisible()
    const originalLinks = await page.locator('.score-list a').evaluateAll(links => links.map(link => link.getAttribute('href')).sort())
    const toggle = page.getByRole('button', { name: '切换曲库展示方式' })
    await expect(toggle).toHaveText('')
    await expect(toggle.locator('svg')).toHaveCount(1)
    await expect(toggle).toHaveAttribute('title', '切换为分类展示')
    const toolbar = page.locator('.library-toolbar')
    const toolbarBounds = await toolbar.boundingBox()
    const searchBounds = await page.getByRole('searchbox', { name: '搜索乐谱' }).boundingBox()
    const toggleBounds = await toggle.boundingBox()
    expect(toggleBounds!.x).toBeGreaterThanOrEqual(searchBounds!.x + searchBounds!.width)
    expect(Math.abs(toggleBounds!.y + toggleBounds!.height / 2 - searchBounds!.y - searchBounds!.height / 2)).toBeLessThan(1)
    await toggle.click()
    await expect(toggle).toHaveAttribute('title', '切换为字母顺序')
    expect(await toolbar.boundingBox()).toEqual(toolbarBounds)
    expect(await page.getByRole('searchbox', { name: '搜索乐谱' }).boundingBox()).toEqual(searchBounds)
    expect(await toggle.boundingBox()).toEqual(toggleBounds)
    await expect(toggle).not.toHaveAttribute('aria-pressed')
    await expect(page.getByRole('navigation', { name: '乐谱首字母索引' })).toHaveCount(0)
    await expect(page.locator('.library-group-heading')).toHaveText([
      '基础练习与入门', '民歌与经典歌曲', '流行歌曲', '影视动漫与游戏', '古典与器乐', '舞曲与节奏',
    ])
    expect(await page.locator('.score-list a').evaluateAll(links => links.map(link => link.getAttribute('href')).sort())).toEqual(originalLinks)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath('library-categories.png'), fullPage: true })
    await page.reload()
    await expect(toggle).toHaveAttribute('title', '切换为字母顺序')
    await page.getByRole('searchbox', { name: '搜索乐谱' }).fill('小星星')
    await expect(page.locator('.library-group-heading')).toHaveText('基础练习与入门')
    await expect(page.locator('.score-list a')).toHaveCount(1)
    await toggle.click()
    await expect(page.locator('.library-group-heading')).toHaveText('X')
    await page.getByRole('searchbox', { name: '搜索乐谱' }).fill('')
    await expect(page.getByRole('navigation', { name: '乐谱首字母索引' })).toBeVisible()
  })
}
