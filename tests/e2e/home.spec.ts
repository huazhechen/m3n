import { expect, test } from '@playwright/test'
import { openScoreSettings, selectNotationMode } from './score-settings'

for (const width of [390, 1280]) {
  test(`home page introduces features before the playable score at ${width}px`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 900 })
    await page.addInitScript(() => {
      localStorage.setItem('m3n:score-width', '1000')
      localStorage.setItem('m3n:render-mode', 'continuous')
    })
    await page.goto('/')
    const actions = page.locator('.hero-actions a')
    await expect(actions).toHaveText(['浏览乐谱库', '打开编辑器'])
    await expect(actions.nth(0)).toHaveAttribute('href', '/scores')
    await expect(actions.nth(0)).toHaveClass('primary-link')
    await expect(actions.nth(1)).toHaveAttribute('href', '/editor')
    await expect(page.locator('.top-nav').getByRole('link', { name: '文档', exact: true })).toHaveCount(0)
    await expect(page.locator('.hero-actions .primary-link')).toHaveCount(1)

    const sample = page.getByRole('region', { name: '用一首《欢乐颂》，开始今天的练习' })
    await expect(sample.getByRole('heading', { level: 2, name: '用一首《欢乐颂》，开始今天的练习', exact: true })).toBeVisible()
    await expect(sample).toHaveClass(/markdown-panel/)
    await expect(sample).toHaveCSS('background-color', 'rgb(255, 255, 255)')
    const features = page.getByLabel('M3N 功能')
    await expect(features.locator('h2')).toHaveText([
      '从一首喜欢的歌开始', '让谱面合你的习惯', '先听一遍，再跟上节拍',
      '把调好的谱，带到谱架上', '把脑海里的旋律写下来',
    ])
    for (const feature of ['固定调', '分页', '小节号', '页面宽度', '音色', '节拍器', '速度', '移调', 'PNG', 'PDF']) {
      await expect(features).toContainText(feature)
    }
    await expect(features.getByRole('link', { name: '浏览指南' })).toHaveAttribute('href', '/?doc=guide')
    await expect(features.getByRole('link', { name: '查阅手册' })).toHaveAttribute('href', '/?doc=manual')
    await expect(features.locator('.home-control-hint svg').first()).toBeVisible()
    await expect(features.getByRole('button')).toHaveCount(0)
    const sampleBounds = await sample.boundingBox()
    const featureBounds = await features.boundingBox()
    expect(sampleBounds!.y).toBeGreaterThanOrEqual(featureBounds!.y + featureBounds!.height)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    const paper = sample.locator('.score-paper')
    await expect(paper.locator('svg').first()).toBeVisible()
    await expect(paper).toHaveAttribute('data-render-mode', 'continuous')
    await expect(paper).toHaveAttribute('data-reading-fit', 'false')
    // The shared full score includes the middle phrase, final held note and bass.
    expect(await paper.locator('g.note[data-m3n-id^="m3n-e-"]').count()).toBeGreaterThan(100)
    await expect(sample.locator('.cm-editor, textarea, .editor-source-pane')).toHaveCount(0)
    await expect(sample.locator('.diagnostics')).toHaveCount(0)
    const controls = page.getByRole('group', { name: '乐谱控制', exact: true })
    await expect(controls).toHaveCSS('position', 'sticky')
    await expect(sample.getByRole('group', { name: '乐谱控制', exact: true })).toHaveCount(1)
    await expect(page.locator('body > .floating-controls')).toHaveCount(0)
    await expect(sample.getByRole('link', { name: '查看曲库中的高音版' })).toHaveCount(0)
    const initialControls = (await controls.boundingBox())!
    expect(initialControls.y).toBeGreaterThanOrEqual(sampleBounds!.y)
    await sample.scrollIntoViewIfNeeded()
    const cardBounds = (await sample.boundingBox())!
    const controlBounds = (await controls.boundingBox())!
    expect(controlBounds.x).toBeGreaterThanOrEqual(cardBounds.x)
    expect(controlBounds.x + controlBounds.width).toBeLessThanOrEqual(cardBounds.x + cardBounds.width)
    expect(controlBounds.y).toBeGreaterThanOrEqual(cardBounds.y)
    expect(controlBounds.y + controlBounds.height).toBeLessThanOrEqual(cardBounds.y + cardBounds.height)
    await controls.getByRole('button', { name: '乐谱设置', exact: true }).click()
    const settings = page.getByRole('dialog', { name: '乐谱设置', exact: true })
    await expect(settings.getByRole('button', { name: /^选择音色，当前/ })).toBeVisible()
    await settings.getByRole('slider', { name: '播放速度', exact: true }).fill('90')
    await expect(paper).not.toHaveAttribute('aria-busy', 'true')
    await openScoreSettings(page)
    await expect(settings.getByRole('slider', { name: '播放速度', exact: true })).toHaveValue('90')
    await settings.getByRole('switch', { name: '分页', exact: true }).click()
    await expect(paper).toHaveAttribute('data-render-mode', 'paged')
    await selectNotationMode(page, '固定调')
    await expect(paper).toHaveAttribute('data-fixed-do', 'true')
    await expect(paper).not.toHaveAttribute('aria-busy', 'true')
    await openScoreSettings(page)
    await settings.getByRole('switch', { name: '小节号', exact: true }).click()
    await expect(paper).toHaveAttribute('data-measure-numbers', 'true')
    await openScoreSettings(page)
    await expect(settings.getByRole('button', { name: /^移调，当前/ })).toBeVisible()
    await expect(settings.getByRole('slider', { name: '乐谱宽度', exact: true })).toBeVisible()
    await page.keyboard.press('Escape')
    await controls.getByRole('button', { name: '播放', exact: true }).click()
    await expect(controls.getByRole('button', { name: '暂停', exact: true })).toBeEnabled({ timeout: 30_000 })
    await controls.getByRole('button', { name: '暂停', exact: true }).click()
    await page.screenshot({ path: info.outputPath('home.png'), fullPage: true })
    await page.evaluate(() => window.scrollTo(0, 0))
    expect((await controls.boundingBox())!.y).toBeGreaterThanOrEqual((await sample.boundingBox())!.y)
  })
}

test('guide and manual open inside the home page by links and direct URLs', async ({ page }) => {
  await page.goto('/')
  await page.locator('.home-feature-links').getByRole('link', { name: '浏览指南' }).click()
  await expect(page).toHaveURL(/\/?\?doc=guide/)
  await expect(page.getByRole('heading', { name: 'M3N 指南', exact: true })).toBeVisible()
  await expect(page.locator('.hero, .hero-actions')).toHaveCount(0)
  await expect(page.getByRole('region', { name: '用一首《欢乐颂》，开始今天的练习' })).toHaveCount(0)
  await expect(page.locator('.top-nav')).toHaveCount(1)
  await page.getByRole('link', { name: '手册 §6', exact: true }).click()
  await expect(page).toHaveURL(/\?doc=manual#6/)
  await expect(page.getByRole('heading', { name: 'M3N 手册', exact: true })).toBeAttached()
  await expect(page.locator('.toc-root')).toHaveCount(2)
  await page.locator('.brand-mark').click()
  await expect(page.getByRole('region', { name: '用一首《欢乐颂》，开始今天的练习' })).toBeVisible()
  await page.locator('.home-feature-links').getByRole('link', { name: '查阅手册' }).click()
  await expect(page).toHaveURL(/\?doc=manual$/)
  await expect(page.getByRole('heading', { name: 'M3N 手册', exact: true })).toBeVisible()
  await page.goto('/?doc=guide')
  await expect(page).toHaveURL(/\?doc=guide$/)
  await expect(page.getByRole('heading', { name: 'M3N 指南', exact: true })).toBeVisible()
})
