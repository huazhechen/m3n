import { expect, test } from '@playwright/test'

test('mobile menu holds navigation and score actions in a single compact header', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/scores/huan_le_song_01')
  const menu = page.locator('.top-nav-menu')
  const toggle = page.getByRole('button', { name: '页面菜单' })
  await expect(toggle).toBeVisible()
  await expect(menu).not.toBeVisible()
  await expect(page.getByRole('link', { name: '文档', exact: true })).not.toBeVisible()
  await expect(page.getByRole('button', { name: '打印', exact: true })).not.toBeVisible()
  expect((await page.locator('.top-nav').boundingBox())!.height).toBeLessThanOrEqual(49)
  await toggle.click()
  for (const name of ['上一曲', '下一曲', '编辑', '乐谱库']) await expect(menu.getByRole('link', { name, exact: true })).toBeVisible()
  await expect(menu.getByRole('button', { name: '打印', exact: true })).toBeVisible()
  await page.screenshot({ path: info.outputPath('mobile-page-menu.png') })
  await page.keyboard.press('Escape')
  await expect(menu).not.toBeVisible()
  await expect(toggle).toBeFocused()
  await toggle.press('Enter')
  await menu.getByRole('button', { name: '打印', exact: true }).click()
  await expect(page.getByRole('button', { name: '关闭打印' })).toBeVisible()
  await expect(menu).not.toBeVisible()
  await page.getByRole('button', { name: '关闭打印' }).click()
  await toggle.click()
  const next = await menu.getByRole('link', { name: '下一曲', exact: true }).getAttribute('href')
  await menu.getByRole('link', { name: '下一曲', exact: true }).click()
  await expect(page).toHaveURL(next!)
  await expect(menu).not.toBeVisible()
  await toggle.click()
  await menu.getByRole('link', { name: '乐谱库', exact: true }).click()
  await expect(page).toHaveURL(/\/scores$/)
  await expect(page.locator('.top-nav-menu')).not.toBeVisible()
  await page.getByRole('button', { name: '页面菜单' }).click()
  await page.setViewportSize({ width: 1280, height: 900 })
  await expect(page.getByRole('button', { name: '页面菜单' })).not.toBeVisible()
  await expect(page.getByRole('link', { name: '文档', exact: true })).toHaveCount(0)
  await expect(page.getByRole('link', { name: '乐谱库', exact: true })).toBeVisible()
})
