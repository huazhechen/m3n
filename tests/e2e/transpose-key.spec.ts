import { expect, test } from '@playwright/test'

test('key dialog offers twelve keys, restores focus and chooses nearest shifts from original D', async ({ page }) => {
  await page.goto('/editor')
  await page.getByLabel('M3N source').fill('{key=D}{4/4}\nN: 1 2 3 4 |||')
  const trigger = page.getByRole('button', { name: /^移调，当前/ })
  await expect(trigger).toHaveText('D')
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: '选择调性' })
  const keys = dialog.locator('.transpose-key-grid button')
  await expect(keys).toHaveText(['C', 'D♭', 'D', 'E♭', 'E', 'F', 'F♯', 'G', 'A♭', 'A', 'B♭', 'B'])
  await expect(dialog.getByRole('button', { name: 'D', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(trigger).toBeFocused()
  await trigger.press('Enter')
  await dialog.getByRole('button', { name: 'B', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(trigger).toBeFocused()
  await expect(trigger).toHaveText('B')
  await expect.poll(() => page.evaluate(() => localStorage.getItem('m3n:playback-transpose'))).toBe('-3')
  await trigger.click()
  await expect(dialog.getByRole('button', { name: 'B', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await dialog.getByRole('button', { name: 'A♭', exact: true }).click()
  await expect.poll(() => page.evaluate(() => localStorage.getItem('m3n:playback-transpose'))).toBe('6')
  await trigger.click()
  await dialog.getByRole('button', { name: 'D', exact: true }).click()
  await expect.poll(() => page.evaluate(() => localStorage.getItem('m3n:playback-transpose'))).toBe('0')
  await trigger.click()
  await page.mouse.click(2, 2)
  await expect(dialog).not.toBeVisible()
  await page.setViewportSize({ width: 320, height: 700 })
  await page.getByRole('tab', { name: '预览', exact: true }).click()
  await trigger.click()
  const bounds = await dialog.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(320)
  await dialog.getByRole('button', { name: '关闭调性选择' }).click()
  await expect(trigger).toBeFocused()
})
