import { waitForEditor } from './editor-state'
import { navigateScore } from './score-navigation'
import { expect, test } from '@playwright/test'
import { openScoreSettings } from './score-settings'

test('key dialog offers a circle of fifths, restores focus on cancellation and chooses nearest shifts from original D', async ({ page }) => {
  await page.goto('/editor')
  await waitForEditor(page)
  await page.getByLabel('M3N source').fill('{key=D}{4/4}\nN: 1 2 3 4 |||')
  await openScoreSettings(page)
  const trigger = page.getByRole('button', { name: /^移调，当前/ })
  await openScoreSettings(page)
  await expect(trigger.locator('.transpose-key-icon')).toHaveText('D')
  await openScoreSettings(page)
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: '选择调性' })
  const keys = dialog.locator('.fifths-key')
  await expect(keys).toHaveText(['C', 'Am', 'G', 'Em', 'D', 'Bm', 'A', 'F♯m', 'E', 'C♯m', 'B', 'G♯m', 'F♯', 'D♯m', 'D♭', 'B♭m', 'A♭', 'Fm', 'E♭', 'Cm', 'B♭', 'Gm', 'F', 'Dm'])
  await expect(dialog.getByRole('button', { name: 'D大调', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await openScoreSettings(page)
  await expect(trigger).toBeFocused()
  await openScoreSettings(page)
  await trigger.press('Enter')
  await dialog.getByRole('button', { name: 'B大调', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await openScoreSettings(page)
  await expect(trigger.locator('.transpose-key-icon')).toHaveText('B')
  await openScoreSettings(page)
  await trigger.click()
  await expect(dialog.getByRole('button', { name: 'B大调', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await dialog.getByRole('button', { name: 'Fm小调', exact: true }).click()
  await openScoreSettings(page)
  await expect(trigger.locator('.transpose-key-icon')).toHaveText('A♭')
  await openScoreSettings(page)
  await trigger.click()
  await dialog.getByRole('button', { name: 'D大调', exact: true }).click()
  await openScoreSettings(page)
  await expect(trigger.locator('.transpose-key-icon')).toHaveText('D')
  await openScoreSettings(page)
  await trigger.click()
  await page.mouse.click(2, 2)
  await expect(dialog).not.toBeVisible()
  await page.setViewportSize({ width: 320, height: 700 })
  await page.getByRole('tab', { name: '预览', exact: true }).click()
  await openScoreSettings(page)
  await trigger.click()
  const bounds = await dialog.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(320)
  const sectors = await keys.all()
  for (const sector of sectors) {
    const box = (await sector.boundingBox())!
    expect(box.x).toBeGreaterThanOrEqual(bounds!.x)
    expect(box.x + box.width).toBeLessThanOrEqual(bounds!.x + bounds!.width)
  }
  await dialog.getByRole('button', { name: '关闭调性选择' }).click()
  await openScoreSettings(page)
  await expect(trigger).toBeFocused()
})


