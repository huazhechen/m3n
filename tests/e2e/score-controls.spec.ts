test('floating transport stays visible and settings open without shifting the score', async ({ page }, info) => {
  await page.goto('/scores/huan_le_song_01')
  const bar = page.getByRole('group', { name: '乐谱控制', exact: true })
  const panel = page.getByRole('dialog', { name: '乐谱设置', exact: true })
  const settings = page.getByRole('button', { name: '乐谱设置', exact: true })
  await expect(bar).toBeVisible()
  await expect(panel).not.toBeVisible()
  await expect(bar.getByRole('slider')).toHaveCount(1)
  await expect(bar.getByRole('switch')).toHaveCount(1)
  await expect(bar.getByRole('switch', { name: '节拍器' })).toBeChecked()
  await expect(page.locator('.score-paper')).toHaveAttribute('data-render-mode', 'paged')
  for (const width of [320, 390, 768, 1280]) {
    await page.setViewportSize({ width, height: 900 })
    const transport = bar.locator('.control-transport')
    const positions = await transport.evaluate(element => [...element.children].map(child => {
      const b = child.getBoundingClientRect(); return { left: b.left, right: b.right, center: b.y + b.height / 2 }
    }))
    expect(positions[0]!.right).toBeLessThan(positions[1]!.left)
    expect(positions[1]!.right).toBeLessThan(positions[2]!.left)
    expect(Math.max(...positions.map(b => b.center)) - Math.min(...positions.map(b => b.center))).toBeLessThan(1)
    const paper = page.locator('.score-paper')
    const before = await paper.boundingBox()
    await settings.click()
    await expect(settings).toHaveAttribute('aria-expanded', 'true')
    await expect(panel.getByRole('slider')).toHaveCount(2)
    await expect(panel.locator('.control-options > button')).toHaveCount(5)
    await expect(panel.locator('.control-options > button')).toHaveText(['合成', '分页', /首调/, '小节号', /调号/])
    await expect(panel.locator('.transpose-key-icon')).toHaveText('G')
    expect(await paper.boundingBox()).toEqual(before)
    const popupBounds = (await panel.boundingBox())!
    expect(popupBounds.x).toBeGreaterThanOrEqual(0)
    expect(popupBounds.x + popupBounds.width).toBeLessThanOrEqual(width)
    expect(popupBounds.y).toBeGreaterThanOrEqual(0)
    expect(popupBounds.y + popupBounds.height).toBeLessThan((await bar.boundingBox())!.y)
    if ([390, 1280].includes(width)) await page.screenshot({ path: info.outputPath(`floating-controls-${width}.png`) })
    await page.keyboard.press('Escape')
    await expect(panel).not.toBeVisible()
    await expect(settings).toBeFocused()
  }
  await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight))
  const bounds = (await bar.boundingBox())!
  expect(bounds.y + bounds.height).toBeLessThanOrEqual(900)
  expect(bounds.y + bounds.height).toBeGreaterThan(875)
  await settings.press('Enter')
  await expect(panel).toBeVisible()
  await page.getByRole('switch', { name: '节拍器' }).click()
  await expect(panel).not.toBeVisible()
  await expect(page.getByRole('switch', { name: '节拍器' })).not.toBeChecked()
})

test('BPM resets on reopening while switches persist; speed reset leaves other settings intact', async ({ page }) => {
  await page.addInitScript(() => {
    if (localStorage.getItem('m3n:metronome-enabled') === null) localStorage.setItem('m3n:metronome-enabled', '0')
    if (localStorage.getItem('m3n:render-mode') === null) localStorage.setItem('m3n:render-mode', 'continuous')
  })
  await page.goto('/scores/huan_le_song_01')
  await openScoreSettings(page)
  const bpm = page.getByRole('slider', { name: '播放速度', exact: true })
  await openScoreSettings(page)
  const speed = page.getByRole('slider', { name: '播放速度', exact: true })
  await openScoreSettings(page)
  const original = await bpm.inputValue()
  await openScoreSettings(page)
  const trigger = page.getByRole('button', { name: /^移调，当前/ })
  await openScoreSettings(page)
  const originalKey = await trigger.locator('.transpose-key-icon').textContent()
  await openScoreSettings(page)
  for (const value of ['10', '240', '137']) { await bpm.fill(value); await expect(speed).toHaveValue(value) }
  await expect(page.locator('.audio-controls input:not([type=range])')).toHaveCount(0)
  await openScoreSettings(page)
  await speed.fill('137')
  await openScoreSettings(page)
  await page.getByRole('button', { name: /^移调，当前/ }).click()
  await page.getByRole('dialog', { name: '选择调性' }).getByRole('button', { name: 'D大调', exact: true }).click()
  await page.getByRole('switch', { name: '节拍器' }).click()
  await openScoreSettings(page)
  await page.getByRole('switch', { name: '小节号', exact: true }).click()
  await openScoreSettings(page)
  await page.getByRole('switch', { name: '分页', exact: true }).click()
  await expect(page.locator('.score-paper')).toHaveAttribute('data-render-mode', 'paged')
  await expect(page.locator('.score-paper')).toHaveAttribute('data-measure-numbers', 'true')
  await expect(page.locator('.score-paper')).not.toHaveAttribute('aria-busy', 'true')
  expect(await page.locator('.score-paper text[font-size="10"]').count()).toBeGreaterThan(0)
  await page.reload()
  await openScoreSettings(page)
  await expect(bpm).toHaveValue(original)
  await openScoreSettings(page)
  for (const name of ['节拍器', '小节号', '分页']) await expect(page.getByRole('switch', { name, exact: true })).toBeChecked()
  await openScoreSettings(page)
  await page.getByRole('button', { name: '还原速度' }).click()
  await openScoreSettings(page)
  await expect(bpm).toHaveValue(original)
  await openScoreSettings(page)
  await expect(trigger.locator('.transpose-key-icon')).toHaveText(originalKey!)
  await expect(page.getByRole('switch', { name: '节拍器' })).toBeChecked()
  await openScoreSettings(page)
  await page.getByRole('switch', { name: '小节号', exact: true }).click()
  await expect(page.locator('.score-paper')).not.toHaveAttribute('aria-busy', 'true')
  await expect(page.locator('.score-paper text[font-size="10"]')).toHaveCount(0)
})

