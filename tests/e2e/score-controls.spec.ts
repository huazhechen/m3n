test('documentation examples reflow to a shared width with readable notes and no horizontal scrolling', async ({ page }) => {
  const fonts: string[] = []
  page.on('request', request => { if (/\.sf3/.test(request.url())) fonts.push(request.url()) })
  await page.addInitScript(() => {
    localStorage.setItem('m3n:playback-tone', 'piano')
    localStorage.setItem('m3n:playback-bpm', '10')
    localStorage.setItem('m3n:playback-transpose', '12')
    localStorage.setItem('m3n:metronome-enabled', '1')
    localStorage.setItem('m3n:measure-numbers', '1')
    localStorage.setItem('m3n:score-width', '1000')
    localStorage.setItem('m3n:fit-width', '1')
    localStorage.setItem('m3n:render-mode', 'paged')
  })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/?doc=guide')
  const example = page.locator('.document-example').first()
  const controls = example.locator('.audio-controls')
  await expect(controls.getByRole('slider')).toHaveCount(1)
  await expect(controls.getByRole('button')).toHaveCount(1)
  await expect(controls.getByRole('switch', { name: '节拍器' })).toHaveAttribute('aria-checked', 'false')
  await expect(controls).toHaveCSS('position', 'sticky')
  await expect(controls).toHaveCSS('top', '0px')
  await expect(controls.locator('.control-transport')).toHaveCSS('border-radius', '10px')
  await controls.getByRole('switch', { name: '节拍器' }).click()
  await expect(controls.getByRole('switch', { name: '节拍器' })).toHaveAttribute('aria-checked', 'true')
  const paper = example.locator('.score-paper')
  await expect.poll(async () => paper.evaluate(element => {
    const svg = element.querySelector('svg')!
    const width = element.getBoundingClientRect().width
    const renderedWidth = Number(svg.getAttribute('width'))
    const mouse = matchMedia('(hover: hover) and (pointer: fine)').matches
    const buttonSize = Math.min(mouse ? 36 : 48, Math.max(mouse ? 24 : 36, Math.min(window.innerWidth, window.innerHeight) / 16))
    return Math.abs(renderedWidth - Math.max(320, Math.round(width * 22 / (buttonSize / 2))))
  })).toBeLessThanOrEqual(1)
  expect(await paper.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await expect(paper).toHaveAttribute('data-reading-fit', 'false')
  await expect(paper).toHaveAttribute('data-render-mode', 'continuous')
  await expect(paper).toHaveAttribute('data-measure-numbers', 'false')
  const alignment = await example.evaluate(element => { const controls = element.querySelector('.audio-controls')!.getBoundingClientRect(); const paper = element.querySelector('.score-paper')!.getBoundingClientRect(); return Math.abs(controls.left - paper.left) + Math.abs(controls.right - paper.right) })
  expect(alignment).toBeLessThan(1)
  await controls.evaluate(element => window.scrollBy(0, element.getBoundingClientRect().top + 8))
  await expect.poll(async () => (await controls.boundingBox())!.y).toBeCloseTo(0, 0)
  expect(fonts).toHaveLength(0)
  await controls.getByRole('button', { name: '播放', exact: true }).click()
  await expect(controls.getByRole('button', { name: '暂停', exact: true })).toBeEnabled({ timeout: 30_000 })
  await controls.getByRole('button', { name: '暂停', exact: true }).click()
  await page.setViewportSize({ width: 1280, height: 900 })
  await expect.poll(async () => paper.evaluate(element => {
    const svg = element.querySelector('svg')!
    const width = element.getBoundingClientRect().width
    const renderedWidth = Number(svg.getAttribute('width'))
    const mouse = matchMedia('(hover: hover) and (pointer: fine)').matches
    const buttonSize = Math.min(mouse ? 36 : 48, Math.max(mouse ? 24 : 36, Math.min(window.innerWidth, window.innerHeight) / 16))
    return Math.abs(renderedWidth - Math.max(320, Math.round(width * 22 / (buttonSize / 2))))
  })).toBeLessThanOrEqual(1)
  expect(await paper.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  expect(fonts).toHaveLength(0)
})


test('clicking notes during playback seeks forward and backward and keeps playing', async ({ page }) => {
  await page.goto('/editor')
  await page.getByLabel('M3N source').fill('{4/4}{60qpm}\nN: 1 2 3 4 | 5 6 7 1e | 2e 3e 4e 5e |||')
  const paper = page.locator('.score-paper')
  await expect(paper).not.toHaveAttribute('aria-busy', 'true')
  const notes = paper.locator('g.note[data-m3n-id^="m3n-e-"]')
  await expect(notes).toHaveCount(12)
  const progress = page.getByRole('slider', { name: '播放位置' })
  await page.getByRole('button', { name: '播放', exact: true }).click()
  const pause = page.getByRole('button', { name: '暂停', exact: true })
  await expect(pause).toBeVisible({ timeout: 30_000 })
  await notes.nth(8).click()
  await expect.poll(async () => Number(await progress.inputValue())).toBeGreaterThanOrEqual(660)
  await expect(pause).toBeVisible()
  await notes.nth(1).click()
  await expect.poll(async () => Number(await progress.inputValue())).toBeLessThan(250)
  await expect(pause).toBeVisible()
  await pause.click()
  const pausedPosition = await progress.inputValue()
  await notes.nth(8).click()
  await expect(progress).toHaveValue(pausedPosition)
  await expect(page.getByRole('button', { name: '播放', exact: true })).toBeVisible()
})


test('fixed C spelling and measure numbers toggle independently and persist', async ({ page }) => {
  await page.goto('/editor')
  await page.getByLabel('M3N source').fill('{key=D}{4/4}\nN: 1 2 3 4 |||')
  const paper = page.locator('.score-paper')
  await openScoreSettings(page)
  const fixed = page.getByRole('button', { name: /^选择记谱方式，当前/ })
  await openScoreSettings(page)
  const measures = page.getByRole('switch', { name: '小节号', exact: true })
  await expect(paper).not.toHaveAttribute('aria-busy', 'true')
  const digits = () => paper.locator('g.note[data-m3n-id] text').allTextContents()
  await expect.poll(digits).toEqual(['1', '2', '3', '4'])
  await openScoreSettings(page)
  await expect(fixed.locator('svg')).toHaveText('♯')
  await openScoreSettings(page)
  await selectNotationMode(page, '固定调')
  await expect(paper).toHaveAttribute('data-fixed-do', 'true')
  await expect(paper).not.toHaveAttribute('aria-busy', 'true')
  await expect.poll(digits).toEqual(['2', '3', '4', '5'])
  await expect(paper.locator('g.note[data-m3n-id] path')).toHaveCount(1)
  await openScoreSettings(page)
  await expect(measures).not.toBeChecked()
  await openScoreSettings(page)
  await measures.click()
  await expect(paper).not.toHaveAttribute('aria-busy', 'true')
  await openScoreSettings(page)
  await expect(fixed).toHaveAccessibleName('选择记谱方式，当前固定调')
  await openScoreSettings(page)
  await expect(measures).toBeChecked()
  await openScoreSettings(page)
  await selectNotationMode(page, '首调')
  await expect(paper).not.toHaveAttribute('aria-busy', 'true')
  await expect.poll(digits).toEqual(['1', '2', '3', '4'])
  await openScoreSettings(page)
  await expect(measures).toBeChecked()
  await openScoreSettings(page)
  await selectNotationMode(page, '固定调')
  await page.reload()
  await openScoreSettings(page)
  await expect(fixed).toHaveAccessibleName('选择记谱方式，当前固定调')
  await openScoreSettings(page)
  await expect(measures).toBeChecked()
})

test('transposition updates key signatures and fixed C notes without restarting playback', async ({ page }) => {
  await page.goto('/editor')
  await page.getByLabel('M3N source').fill('{key=D}{4/4}{30qpm}\nN: 1 2 3 4 | 5 6 7 1e |||')
  const paper = page.locator('.score-paper')
  const digits = () => paper.locator('g.note[data-m3n-id] text').allTextContents()
  await expect.poll(digits).toEqual(['1', '2', '3', '4', '5', '6', '7', '1'])
  await page.getByRole('button', { name: '播放', exact: true }).click()
  const pause = page.getByRole('button', { name: '暂停', exact: true })
  await expect(pause).toBeVisible({ timeout: 30_000 })
  await openScoreSettings(page)
  await page.getByRole('button', { name: /^移调，当前/ }).click()
  await page.getByRole('dialog', { name: '选择调性' }).getByRole('button', { name: 'E大调', exact: true }).click()
  await expect.poll(() => paper.locator('text').allTextContents()).toContain('E')
  await expect.poll(digits).toEqual(['1', '2', '3', '4', '5', '6', '7', '1'])
  await expect(pause).toBeVisible()
  await openScoreSettings(page)
  await selectNotationMode(page, '固定调')
  await expect.poll(digits).toEqual(['3', '4', '5', '6', '7', '1', '2', '3'])
  await expect.poll(() => paper.locator('text').allTextContents()).toContain('C')
  await openScoreSettings(page)
  await page.getByRole('button', { name: /^移调，当前/ }).click()
  await page.getByRole('dialog', { name: '选择调性' }).getByRole('button', { name: 'E♭大调', exact: true }).click()
  await expect.poll(digits).toEqual(['2', '4', '5', '5', '6', '1', '2', '2'])
  await expect(pause).toBeVisible()
  await pause.click()
})


test('switching songs restores each song’s original tempo and default width', async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem('m3n:playback-bpm', '137')
    localStorage.setItem('m3n:score-width', '1000')
  })
  const originalUrl = '/scores/huan_le_song_01'
  await page.goto(originalUrl)
  await openScoreSettings(page)
  const bpm = page.getByRole('slider', { name: '播放速度', exact: true })
  await openScoreSettings(page)
  const width = page.getByRole('slider', { name: '乐谱宽度', exact: true })
  await openScoreSettings(page)
  const originalBpm = await bpm.inputValue()
  await openScoreSettings(page)
  await expect(width).toHaveValue('540')
  const nextUrl = await page.getByRole('link', { name: '下一曲', exact: true }).getAttribute('href')
  await page.getByRole('link', { name: '下一曲', exact: true }).click()
  await openScoreSettings(page)
  const nextBpm = await bpm.inputValue()
  await openScoreSettings(page)
  const nextWidth = await width.inputValue()
  await page.goto(originalUrl)
  await openScoreSettings(page)
  await bpm.fill('137')
  await openScoreSettings(page)
  await width.fill('1000')
  await page.getByRole('link', { name: '下一曲', exact: true }).click()
  await expect(page).toHaveURL(nextUrl!)
  await openScoreSettings(page)
  await expect(bpm).toHaveValue(nextBpm)
  await openScoreSettings(page)
  await expect(width).toHaveValue(nextWidth)
  await openScoreSettings(page)
  await bpm.fill('139')
  await openScoreSettings(page)
  await width.fill('1100')
  await page.getByRole('link', { name: '上一曲', exact: true }).click()
  await openScoreSettings(page)
  await expect(bpm).toHaveValue(originalBpm)
  await openScoreSettings(page)
  await expect(width).toHaveValue('540')
})
