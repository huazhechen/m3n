import {test, expect} from '@playwright/test'
import {openScoreSettings, selectNotationMode} from './score-settings'

test('touch-readable text offers a full overview and preserves paged reading across controls',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.goto('scores/hei_se_you_mo_01')
  const reading=page.getByRole('region',{name:'黑色幽默，无障碍读谱',exact:true})
  await reading.locator('summary').filter({hasText:'无障碍读谱'}).click()
  await expect(reading.getByRole('heading',{level:4})).toHaveCount(8)
  await expect(reading).toContainText('第5小节，第2遍房子')
  const paper=page.locator('.score-paper')
  await expect(paper).toHaveAttribute('aria-hidden','true')
  await expect(paper.locator('svg').first()).toBeVisible()
  expect(await paper.ariaSnapshot()).toBe('')
  const snapshot=await reading.ariaSnapshot()
  expect(snapshot).toContain('第1遍歌词“难”')
  expect(snapshot).toContain('音高D5')
  expect(await reading.evaluate(e=>e.getBoundingClientRect().width)).toBeGreaterThan(300)
  const firstNote=reading.locator('li').first()
  await firstNote.scrollIntoViewIfNeeded()
  expect(await firstNote.evaluate(e=>{
    const r=e.getBoundingClientRect()
    return e.contains(document.elementFromPoint(r.x+r.width/2,r.y+r.height/2))
  })).toBe(true)
  const detailedHeading=reading.getByRole('heading',{name:/逐音详解/})
  await reading.getByRole('button',{name:'下一页',exact:true}).click()
  await expect(detailedHeading).toHaveText(/第2页.*第9小节至第16小节/)
  await expect(detailedHeading).toBeFocused()
  await expect(reading).toContainText('第16小节，转调至降D大调')
  await reading.getByLabel('跳转小节范围').selectOption('7')
  await expect(reading.getByRole('heading',{level:4})).toHaveCount(3)
  await expect(reading.getByRole('button',{name:'下一页',exact:true})).toBeDisabled()
  await reading.getByLabel('跳转小节范围').selectOption('0')
  await expect(reading.getByRole('button',{name:'上一页',exact:true})).toBeDisabled()
  await reading.locator('summary').filter({hasText:/^简略全谱$/}).click()
  const overview=reading.locator('.score-accessible-overview')
  await expect(overview.getByRole('heading',{level:3}).last()).toHaveText('第57小节至第59小节')
  await expect(overview).not.toContainText('科学音高记法')
  await reading.locator('summary').filter({hasText:/^简略全谱$/}).click()
  await selectNotationMode(page,'固定调')
  await page.keyboard.press('Escape')
  await expect(reading).toContainText('固定唱名')
  await selectNotationMode(page,'五线谱')
  await page.keyboard.press('Escape')
  await expect(reading.locator('ol').first()).not.toContainText('音级')
  await expect(paper.locator('svg').first()).toBeVisible()
  await openScoreSettings(page)
  await page.getByRole('button',{name:/^移调，当前/}).click()
  await page.getByRole('dialog',{name:'选择调性'}).getByRole('button',{name:'C大调',exact:true}).click()
  await page.keyboard.press('Escape')
  await expect(reading.locator('p').first()).toContainText('调性C大调')
  await expect(reading.locator('li').first()).toContainText('E5')
  await reading.getByRole('button',{name:'下一页',exact:true}).click()
  await openScoreSettings(page)
  await page.keyboard.press('Escape')
  await reading.getByRole('button',{name:'继续阅读本页'}).click()
  await expect(detailedHeading).toHaveText(/第2页/)
  await expect(detailedHeading).toBeFocused()
  await reading.locator('summary').filter({hasText:'无障碍读谱'}).click()
  await reading.locator('summary').filter({hasText:'无障碍读谱'}).click()
  await expect(detailedHeading).toHaveText(/第2页/)
  expect(await reading.locator('[aria-live], li[tabindex]').count()).toBe(0)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
})

test('Turkish March describes its pickup and the following complete second beat',async({page})=>{
  await page.goto('scores/turkish_march_01')
  const reading=page.getByRole('region',{name:'土耳其进行曲，无障碍读谱',exact:true})
  await reading.locator('summary').filter({hasText:'无障碍读谱'}).click()
  await expect(reading.getByRole('heading',{level:4}).first()).toContainText('弱起，共1拍')
  await expect(reading.locator('ol').first().locator('li').first()).toContainText('第2拍')
  const nextBar=reading.locator('ol').nth(1)
  await expect(nextBar.locator('li')).toHaveCount(6)
  await expect(nextBar.locator('li').nth(2)).toContainText('第2拍；来')
  await expect(nextBar.locator('li').last()).toContainText('第2.75拍；哆')
})
