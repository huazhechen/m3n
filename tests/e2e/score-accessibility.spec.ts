import {test, expect} from '@playwright/test'
import {waitForEditor} from './editor-state'
import {openScoreSettings, selectNotationMode} from './score-settings'

test('plain text measures support native folding without exposing the score graphics',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.goto('scores/hei_se_you_mo_01')
  await waitForEditor(page)
  const reading=page.getByRole('region',{name:'黑色幽默，无障碍读谱',exact:true})
  const entry=reading.getByText('无障碍读谱',{exact:true})
  await expect(reading.locator('.score-accessible-measure > summary').first()).not.toBeVisible()
  await entry.focus()
  await page.keyboard.press('Enter')
  const measures=reading.locator('.score-accessible-measure')
  await expect(measures).toHaveCount(59)
  const overview=reading.locator('.score-accessible-overview')
  await expect(overview.locator('h3').first()).not.toBeVisible()
  await overview.locator('summary').click()
  await expect(overview.locator('h3').first()).toHaveText('第1小节至第8小节')
  await expect(overview.locator('section').first().locator('p')).toHaveCount(1)
  await expect(overview).not.toContainText('歌词“难”')
  await overview.locator('summary').click()
  await expect(measures.first().locator('summary')).toHaveText('第1小节')
  await expect(measures.nth(15).locator('summary')).toHaveText('第16小节，转调至降D大调')
  const twentieth=measures.nth(19)
  await twentieth.locator('summary').click()
  await expect(twentieth.locator('p').first()).toBeVisible()
  await expect(measures.first().locator('p').first()).not.toBeVisible()
  // The next native keyboard stop is the next measure, with notes remaining text.
  await page.keyboard.press('Tab')
  await expect(measures.nth(20).locator('summary')).toBeFocused()
  await measures.first().locator('summary').click()
  await expect(measures.first().locator('p').first()).toContainText('第1遍歌词“难”')
  const snapshot=await reading.ariaSnapshot()
  expect(snapshot).toContain('paragraph: 第1拍')
  expect(snapshot).not.toMatch(/img|图像/)
  await expect(page.locator('.score-paper')).toHaveAttribute('aria-hidden','true')
  expect(await page.locator('.score-paper').ariaSnapshot()).toBe('')
  await expect(reading.locator('select, button:not(.score-accessible-toggle), svg, [tabindex], [aria-live]')).toHaveCount(0)
  await openScoreSettings(page)
  await page.keyboard.press('Escape')
  const transport=page.getByRole('group',{name:'乐谱控制',exact:true})
  await transport.getByRole('button',{name:'播放',exact:true}).click()
  const pause=transport.getByRole('button',{name:'暂停',exact:true})
  await expect(pause).toBeVisible({timeout:15000})
  await expect(pause).toBeFocused()
  await expect(twentieth).toHaveAttribute('open','')
  await pause.click()
  await entry.click()
  await entry.click()
  await expect(twentieth.locator('p').first()).toBeVisible()
})

