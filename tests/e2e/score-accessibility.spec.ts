import {test, expect} from '@playwright/test'
import {openScoreSettings, selectNotationMode} from './score-settings'

test('hidden reading follows actual measures and supports overview and direct jumps',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.goto('scores/hei_se_you_mo_01')
  const paper=page.getByRole('region',{name:'黑色幽默，逐小节读谱',exact:true})
  const measures=paper.locator('[data-reading-measure]')
  await expect(measures).toHaveCount(59)
  const first=measures.first()
  await expect(first).toHaveAccessibleName('第1小节，反复开始')
  await expect(first.getByRole('img').first()).toHaveAccessibleName(/第1拍.*音高D5.*第1遍歌词“难”/)
  const snapshot=await paper.ariaSnapshot()
  expect(snapshot).toContain('第16小节，转调至降D大调')
  expect(snapshot).toContain('第1遍歌词“难”')
  expect(snapshot).not.toMatch(/text:.*难/)
  for(const width of [390,800]){
    await page.setViewportSize({width,height:844})
    const note=measures.nth(30).locator('g[role="img"]').first()
    await note.scrollIntoViewIfNeeded()
    const box=await note.boundingBox()
    expect(box!.width).toBeGreaterThan(1)
    expect(box!.height).toBeGreaterThan(1)
    const hit=await note.evaluate(e=>{
      const r=e.getBoundingClientRect()
      return e.contains(document.elementFromPoint(r.x+r.width/2,r.y+r.height/2))
    })
    expect(hit).toBe(true)
    const title=note.locator(':scope > title')
    expect(await title.evaluate(e=>e.getBoundingClientRect().width)).toBe(0)
  }
  const reading=page.getByRole('region',{name:'黑色幽默，无障碍读谱',exact:true})
  await reading.locator('summary').filter({hasText:'无障碍读谱'}).click()
  await expect(reading.locator('ol')).toHaveCount(0)
  await reading.getByLabel('选择小节').selectOption('30')
  await reading.getByRole('button',{name:'跳转到所选小节'}).click()
  await expect(measures.nth(30)).toBeFocused()
  await openScoreSettings(page)
  await page.keyboard.press('Escape')
  const transport=page.getByRole('group',{name:'乐谱控制',exact:true})
  await transport.getByRole('button',{name:'播放',exact:true}).click()
  await expect(transport.getByRole('button',{name:'暂停',exact:true})).toBeVisible({timeout:15000})
  await transport.getByRole('button',{name:'暂停',exact:true}).click()
  await reading.getByRole('button',{name:'继续阅读小节'}).click()
  await expect(measures.nth(30)).toBeFocused()
  // Return also remembers a measure selected directly on the music.
  await measures.nth(40).click()
  await reading.getByRole('button',{name:'继续阅读小节'}).click()
  await expect(measures.nth(40)).toBeFocused()
  await reading.locator('summary').filter({hasText:/^简略全谱$/}).click()
  const overview=reading.locator('.score-accessible-overview')
  await expect(overview.getByRole('heading',{level:3}).last()).toHaveText('第57小节至第59小节')
  await expect(overview).not.toContainText('科学音高记法')
  await reading.locator('summary').filter({hasText:/^简略全谱$/}).click()
  await selectNotationMode(page,'固定调')
  await page.keyboard.press('Escape')
  await expect(first.getByRole('img').first()).toHaveAccessibleName(/固定唱名/)
  await selectNotationMode(page,'五线谱')
  await page.keyboard.press('Escape')
  await expect(paper.locator('svg').first()).toHaveAttribute('data-notation','staff')
  await expect(first.getByRole('img').first()).toHaveAccessibleName(/D5，科学音高记法/)
  await expect(first.getByRole('img').first()).not.toHaveAccessibleName(/音级/)
  await openScoreSettings(page)
  await page.getByRole('button',{name:/^移调，当前/}).click()
  await page.getByRole('dialog',{name:'选择调性'}).getByRole('button',{name:'C大调',exact:true}).click()
  await page.keyboard.press('Escape')
  await expect(first.getByRole('img').first()).toHaveAccessibleName(/E5，科学音高记法/)
  await reading.getByRole('button',{name:'继续阅读小节'}).click()
  await expect(measures.nth(40)).toBeFocused()
  expect(await paper.locator('[aria-live], [tabindex="0"]').count()).toBe(0)
})

test('Turkish March retains its pickup and the following entire second beat on the music',async({page})=>{
  await page.goto('scores/turkish_march_01')
  const paper=page.getByRole('region',{name:'土耳其进行曲，逐小节读谱',exact:true})
  const measures=paper.locator('[data-reading-measure]')
  await expect(measures.first()).toHaveAccessibleName(/弱起，共1拍/,{timeout:30000})
  await expect(measures.first().getByRole('img').first()).toHaveAccessibleName(/^第2拍/)
  const nextBar=measures.nth(1).getByRole('img')
  await expect(nextBar).toHaveCount(6)
  await expect(nextBar.nth(2)).toHaveAccessibleName(/^第2拍；来/)
  await expect(nextBar.last()).toHaveAccessibleName(/^第2.75拍；哆/)
})

test('keyed visits and tuplets remain aligned when switching between compact and expanded displays',async({page})=>{
  await page.goto('editor')
  await page.getByLabel('M3N source').fill('{title=读屏换调测试}{key=C}{2/4}{order=A,A@Db5}\n===A\nN: [1 2 3:2] |||\nL1: 春天好\nL2: 秋天好')
  await page.getByRole('button',{name:'保存',exact:true}).click()
  const paper=page.getByRole('region',{name:'读屏换调测试，逐小节读谱',exact:true})
  await expect(paper.locator('[data-reading-measure]')).toHaveCount(1)
  await expect(paper.getByRole('img')).toHaveCount(1)
  await expect(paper.getByRole('img')).toHaveAccessibleName(/3连音.*歌词“春”/)
  for(const mode of ['固定调','五线谱'] as const){
    await selectNotationMode(page,mode)
    await page.keyboard.press('Escape')
    if(mode==='五线谱') await expect(paper.locator('svg').first()).toHaveAttribute('data-notation','staff')
    await expect(paper.locator('[data-reading-measure]')).toHaveCount(2)
    await expect(paper.getByRole('img')).toHaveCount(2)
    await expect(paper.getByRole('img').last()).toHaveAccessibleName(/3连音.*升C5.*歌词“秋”/)
  }
})
